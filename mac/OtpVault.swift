import AppKit
import UserNotifications

// Marker types from nspasteboard.org: clipboard managers skip concealed and transient items.
extension NSPasteboard.PasteboardType {
    static let concealed = Self("org.nspasteboard.ConcealedType")
    static let transient = Self("org.nspasteboard.TransientType")
    static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
    static let markerSource = Self("org.nspasteboard.source")
    static let devswitchRemote = Self("dev.notsg.devswitch.remote")
}

/// Puts a secret on the clipboard with concealed and transient markers. Returns the new changeCount.
@MainActor @discardableResult func copyConcealed(_ value: String, autoGenerated: Bool = false) -> Int {
    let pasteboard = NSPasteboard.general
    let markers: [NSPasteboard.PasteboardType] = [.concealed, .transient] + (autoGenerated ? [.autoGenerated] : [])
    pasteboard.clearContents()
    pasteboard.declareTypes([.string, .markerSource] + markers, owner: nil)
    pasteboard.setString(value, forType: .string)
    pasteboard.setString("dev.notsg.devswitch", forType: .markerSource)
    markers.forEach { pasteboard.setData(Data(), forType: $0) }
    return pasteboard.changeCount
}

/// Holds the latest phone code in memory only, for at most 90 seconds or until it is used.
/// Digits go to the HUD, the clipboard and the Helium extension; never to a notification, log or UserDefaults.
@MainActor final class OtpVault: ObservableObject {
    static let shared = OtpVault()
    /// What views may show. It never contains the digits.
    @Published private(set) var latest: (source: String, at: Date)?
    var onArrive: (() -> Void)?
    var lifetime: TimeInterval = 90
    private var code: String?
    private var domain: String?
    private var expiry: Timer?

    func receive(_ event: PhoneEvent) {
        guard let code = event.string("code"), (4...12).contains(code.count),
              code.allSatisfy({ $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "-") }) else { return }
        // `source` is the app label or SMS sender; `app` is only a package name.
        let source = event.string("source").flatMap { $0.isEmpty ? nil : $0 } ?? "your phone"
        self.code = code; domain = event.string("domain"); latest = (source, Date())
        expiry?.invalidate()
        expiry = Timer.scheduledTimer(withTimeInterval: lifetime, repeats: false) { [weak self] _ in
            Task { @MainActor in self?.consume() }
        }
        copy()
        banner(source)
        OtpHUD.shared.show(code: code, source: source)
        onArrive?()
    }

    func current() -> (code: String, source: String, domain: String?)? {
        guard let code, let latest, Date().timeIntervalSince(latest.at) < lifetime else { return nil }
        return (code, latest.source, domain)
    }

    func consume() {
        code = nil; domain = nil; latest = nil
        expiry?.invalidate(); expiry = nil
        OtpHUD.shared.close()
    }

    /// Copies the code; the clipboard is cleared after the lifetime unless something else was copied since.
    func copy() {
        guard let code = current()?.code else { return }
        let count = copyConcealed(code, autoGenerated: true)
        DispatchQueue.main.asyncAfter(deadline: .now() + lifetime) {
            if NSPasteboard.general.changeCount == count { NSPasteboard.general.clearContents() }
        }
    }

    // macOS keeps notification text on disk, so the banner names the sender and never carries digits.
    private func banner(_ source: String) {
        let content = UNMutableNotificationContent()
        content.title = "Code from \(source.contains(where: \.isNumber) ? "your phone" : source) — copied"
        content.categoryIdentifier = "otp"
        assert(!content.title.contains(where: \.isNumber) && content.body.isEmpty && content.userInfo.isEmpty)
        UNUserNotificationCenter.current().add(UNNotificationRequest(identifier: "otp", content: content, trigger: nil))
    }
}

extension OtpVault: OtpSource {}
