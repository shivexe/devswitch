import AppKit
import CryptoKit

/// Shared clipboard (research Part B §3). Mac→phone runs on a changeCount timer when enabled; phone→Mac
/// text arrives as a `clipboard` event after a tap on the phone. Clipboard content is never logged.
@MainActor final class ClipboardSync: ObservableObject {
    static let shared = ClipboardSync()
    weak var controller: Controller?
    @Published var enabled = UserDefaults.standard.bool(forKey: "clipboard.sync") {
        didSet { UserDefaults.standard.set(enabled, forKey: "clipboard.sync"); schedule() }
    }
    // Password managers and other apps mark private items with these; DevSwitch marks what it wrote itself.
    private static let skipped: Set<NSPasteboard.PasteboardType> = [.concealed, .transient, .autoGenerated, .devswitchRemote,
        .init("com.agilebits.onepassword"), .init("de.petermaurer.TransientPasteboardType")]
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var lastHash = ""

    /// True when macOS asks or refuses before apps read the clipboard; only the manual send works then.
    var blocked: Bool {
        if #available(macOS 15.4, *) { return [.ask, .alwaysDeny].contains(NSPasteboard.general.accessBehavior) }
        return false
    }

    func start(controller: Controller) { self.controller = controller; schedule() }

    private func schedule() {
        timer?.invalidate(); timer = nil
        guard enabled, !blocked else { return }
        lastCount = NSPasteboard.general.changeCount // never send what was copied before the switch was turned on
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardSync.shared.tick() }
        }
    }

    // Reads content only after the count changes and then stays put for 300 ms.
    private func tick() {
        let count = NSPasteboard.general.changeCount
        guard count != lastCount else { return }
        lastCount = count
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { [weak self] in
            guard let self, self.enabled, NSPasteboard.general.changeCount == count else { return }
            self.send(manual: false)
        }
    }

    /// Sends the clipboard text to the phone. Returns what to tell the user.
    @discardableResult func send(manual: Bool) -> String {
        let pasteboard = NSPasteboard.general
        guard let controller, controller.phone != nil else { return "Pair a phone first." }
        guard Self.skipped.isDisjoint(with: pasteboard.types ?? []) else { return "Passwords and private items are not sent." }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else {
            return pasteboard.types?.isEmpty != false ? "Your clipboard is empty. Copy some text first." : "Only text can be sent. Copy some text first."
        }
        guard text.utf8.count <= 16 * 1024 else { return "Text over 16 KB is not sent." }
        let hash = Self.hash(text)
        // The dev.notsg.devswitch.remote marker and this hash keep phone text from echoing back.
        guard manual || hash != lastHash else { return "" }
        lastHash = hash
        controller.enqueue(OutgoingCommand("setClipboard", ["mime": .string("text/plain"), "text": .string(text), "hash": .string(hash)]))
        return Controller.sendingClipboard
    }

    func receive(_ event: PhoneEvent) {
        guard let text = event.string("text"), !text.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, .devswitchRemote], owner: nil)
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: .devswitchRemote)
        lastHash = Self.hash(text)
    }

    private static func hash(_ text: String) -> String {
        SHA256.hash(data: Data(text.utf8)).map { String(format: "%02x", $0) }.joined()
    }
}
